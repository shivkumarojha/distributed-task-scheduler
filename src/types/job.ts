/**
 * Domain types for the task scheduler.
 *
 * Keeping these in one place means every layer (producer, queue engine,
 * workers, dashboard) agrees on the exact shape of a job. Change it here and
 * TypeScript will point at every place that needs updating.
 */

/**
 * The payload a job carries. Deliberately `Record<string, unknown>` rather
 * than `any`: the *shape* is app-specific, but it must always be a JSON
 * object (Redis stores it as a string, so it must be serialisable).
 */
export type JobData = Record<string, unknown>;

/** Priority scale. 1 = low, 10 = critical (matches the spec). */
export const MIN_PRIORITY = 1;
export const MAX_PRIORITY = 10;
export const DEFAULT_PRIORITY = 5;

/** How many times a job may run before it is considered permanently failed. */
export const DEFAULT_MAX_ATTEMPTS = 3;

/**
 * A fully-formed job as it exists inside Redis.
 *
 * `id` and `createdAt` are generated by the engine, never by the caller, so a
 * caller cannot forge colliding ids.
 */
export interface Job<TData extends JobData = JobData> {
  /** Globally-unique id (UUID v4). Also used as the ZSET member identity. */
  id: string;
  /** Logical task name, e.g. "email:send" — routed to a handler later. */
  type: string;
  /** Arbitrary JSON payload for the handler. */
  data: TData;
  /** 1 (low) .. 10 (critical). */
  priority: number;
  /** Delay before the job becomes runnable, in milliseconds. 0 = immediate. */
  delay: number;
  /** How many times this job has already been attempted. */
  attempts: number;
  /** Attempt ceiling before the job is moved to the dead-letter queue. */
  maxAttempts: number;
  /** Unix epoch milliseconds the job was created. */
  createdAt: number;
}

/**
 * What a *producer* is allowed to supply. Everything is optional except
 * `type`; the engine fills in `id`, `attempts` and `createdAt`.
 */
export interface CreateJobInput<TData extends JobData = JobData> {
  type: string;
  data?: TData;
  priority?: number;
  delay?: number;
  maxAttempts?: number;
}

/**
 * Lifecycle states a job can be in. Persisted in Redis in later phases
 * (processing HASH / DLQ); declared here so the whole system shares one
 * vocabulary.
 */
export type JobState =
  | 'active'
  | 'delayed'
  | 'processing'
  | 'completed'
  | 'failed'
  | 'dead';
